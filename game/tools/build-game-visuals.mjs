#!/usr/bin/env node
// Inventory only the user's uploaded images. No downloading, renaming or sprite edits.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const game = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const names = JSON.parse(readFileSync(resolve(game, 'tools/person-names-ja.json'), 'utf8'));
const pngs = folder => readdirSync(resolve(game, 'assets', folder)).filter(file => file.endsWith('.png')).sort();
const people = folder => pngs(folder).map(file => {
  const match = file.match(/^portrait_([a-z]{3})_(.+?)(?:_result)?\.png$/i);
  const country = match ? match[1].toUpperCase() : 'GENERIC';
  const key = match ? match[2].toLowerCase() : file.replace(/^portrait_|\.png$/gi, '').toLowerCase();
  const name = names[folder][key];
  if (!name) throw new Error(`Japanese name missing: ${file}`);
  return { id: country.toLowerCase() + '_' + key, country, name, file };
});
const technology = pngs('technology');
const data = {
  flags: pngs('flags'), operatives: people('operatives'), scientists: people('scientists'),
  projects: pngs('special_projects'), technology,
  units: Object.fromEntries(pngs('land_units').map(file => {
    const bytes = readFileSync(resolve(game, 'assets/land_units', file));
    return [file, { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) }];
  }))
};
writeFileSync(resolve(game, 'assets/game-asset-data.js'), '// Generated by tools/build-game-visuals.mjs.\nconst GameAssetData = '+JSON.stringify(data,null,2)+';\nif (typeof module !== "undefined") module.exports = GameAssetData;\n');
console.log(`Flags: ${data.flags.length}; operatives: ${data.operatives.length}; scientists: ${data.scientists.length}; blueprints: ${data.projects.length}; technology: ${data.technology.length}; units: ${Object.keys(data.units).length}`);
